// Run with: node scripts/check-ui.cjs <path-to-playwright-or-playwright-core>
const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100}});
  const errors=[];
  const screenshot = async path => {
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path,fullPage:true,animations:'disabled'});
  };
  page.on('pageerror', error=>errors.push(error.message));
  fs.mkdirSync('docs/screenshots',{recursive:true});
  try {
    await page.goto('http://127.0.0.1:8015');
    await page.locator('#sample').waitFor();
    assert.equal(await page.locator('.tool-card input:checked').count(),0);
    await screenshot('docs/screenshots/new-employee-desktop.png');
    await page.click('#help-open');
    assert(await page.locator('#help-dialog').isVisible());
    await page.click('.guide-done');
    await page.click('#sample');
    assert.equal(await page.locator('.tool-card input:checked').count(),4);
    await page.click('#recommended-mode');
    assert(await page.locator('#manual-access-panel').isHidden());
    await page.fill('#responsibilities','Review engineering tasks and write code.');
    await page.click('#manual-mode');
    assert(await page.locator('#recommended-access-panel').isHidden());
    assert.equal(await page.locator('.tool-card input:checked').count(),4);
    await page.click('#recommended-mode');
    assert.equal(await page.locator('#responsibilities').inputValue(),'Review engineering tasks and write code.');
    await page.click('#manual-mode');
    await page.click('#plan-button');
    await page.waitForURL('**/approval?id=*');
    await page.locator('#approve').waitFor();
    assert(await page.locator('#approve').isDisabled());
    await page.locator('.review-row .remove').first().click();
    assert.equal(await page.locator('.review-row:visible').count(),3);
    await page.getByRole('button',{name:'Undo',exact:true}).click();
    assert.equal(await page.locator('.review-row:visible').count(),4);
    await page.click('#reset-plan');
    await page.locator('.review-row select').first().selectOption('member');
    assert(await page.locator('#approve').isDisabled());
    await page.click('#save-plan');
    await page.waitForFunction(()=>document.querySelector('#save-plan').disabled);
    await page.locator('#confirm').check();
    assert(await page.locator('#approve').isEnabled());
    await screenshot('docs/screenshots/review-desktop.png');
    await page.click('#approve');
    await page.waitForURL('**/dashboard?id=*');
    await page.locator('.outcome.completed').waitFor();
    await page.click('.audit-details summary');
    assert(await page.locator('.log').first().isVisible());
    await screenshot('docs/screenshots/results-desktop.png');
    await page.goto('http://127.0.0.1:8015/');
    await page.click('#sample');
    await page.click('#plan-button');
    await page.waitForURL('**/approval?id=*');
    await page.click('#reject');
    await page.click('#cancel-reject');
    assert(await page.locator('#approve').isDisabled());
    await page.locator('.review-row select').first().selectOption('member');
    await page.click('#reject');
    await page.click('#confirm-reject');
    await page.waitForURL('**/dashboard?id=*');
    await page.locator('.outcome.rejected').waitFor();
    assert(await page.locator('.stats').isHidden());
    await page.goto('http://127.0.0.1:8015/dashboard');
    await page.locator('#request-search').waitFor();
    await page.selectOption('#request-filter','rejected');
    assert((await page.locator('[data-request-id]:visible').count())>=1);
    await page.fill('#request-search','no-such-person');
    assert(await page.locator('#no-matches').isVisible());
    await page.click('#clear-filters');
    assert((await page.locator('[data-request-id]:visible').count())>=2);
    await screenshot('docs/screenshots/requests-desktop.png');
    await page.goto('http://127.0.0.1:8015/');
    await page.click('#sample');
    await page.click('#recommended-mode');
    await page.fill('#responsibilities','Build applications, review code and track engineering tasks.');
    await page.click('#recommend-access');
    await page.waitForURL('**/approval?id=*');
    await page.locator('.recommendation-reason').first().waitFor();
    assert.equal(await page.locator('.recommendation-reason').count(),4);
    assert(await page.locator('#approve').isDisabled());
    await screenshot('docs/screenshots/recommended-access.png');
    await page.setViewportSize({width:390,height:844});
    await page.goto('http://127.0.0.1:8015');
    await page.locator('#sample').waitFor();
    assert(await page.locator('.mobile-nav').isVisible());
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    await screenshot('docs/screenshots/new-employee-mobile.png');
    await page.click('#mobile-settings');
    await page.locator('#sim-form').waitFor();
    assert(await page.locator('#simulator').isVisible());
    assert.deepEqual(errors,[]);
    console.log('UI checks passed: guide, sample, editing/undo, approval, rejection, filters, mobile navigation and overflow.');
  } finally {
    await browser.close();
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
